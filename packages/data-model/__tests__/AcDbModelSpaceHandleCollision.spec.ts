describe('Model space handle collision with block table (#233)', () => {
  it('keeps *Model_Space findable by handle 2 after DXF read', async () => {
    const db = new AcDbDatabase()
    expect(db.tables.blockTable.objectId).toBe('2')

    acdbHostApplicationServices().workingDatabase = db
    await new AcDbDxfDocumentReader(db).read(
      AcDbDxfFiler.fromString(MODEL_SPACE_HANDLE_2_DXF)
    )

    const modelSpace = db.tables.blockTable.getIdAt('2')
    expect(modelSpace).toBeDefined()
    expect(modelSpace!.name).toBe(AcDbBlockTableRecord.MODEL_SPACE_NAME)
    expect(modelSpace!.ownerId).toBe(db.tables.blockTable.objectId)
    expect(db.tables.blockTable.objectId).not.toBe('2')

    const line = [...modelSpace!.newIterator()][0]
    expect(line).toBeDefined()
    expect(line!.dxfTypeName).toBe('LINE')
  })
})
